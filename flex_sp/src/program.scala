package DSL.flex_sp

import DSL.fl._
import DSL.flex._
import scala.util.parsing.combinator._

// Parses FLEX/SP concrete syntax (s-expressions) into the FLEX/SP AST.
//
// FLEX/SP (Chapter 12.2 of the book) is FLEX/S with universal polymorphism:
// the same concrete syntax as FLEX (Figure 11.31) extended with
//
//   (pabs (τ*) E)      a polymorphic abstraction (Figure 12.9)
//   (pcall E T*)       a polymorphic projection (Figure 12.9)
//   (forall (τ*) T)    a polymorphic type
//
// plus the def-datatype declaration (Figure 12.13)
//
//   (def-datatype τdata (Itag1 T1*) ... (Itagn Tn*))
//
// which desugars, at parse time, to a def-type for the recursive
// sum-of-products type of τdata and, for each clause, a constructor def and
// a polymorphic deconstructor def (Figure 12.11). Per the figure's footnote,
// all def-type declarations (including the ones generated by def-datatype)
// are moved in front of all def declarations, preserving their relative
// order.
//
// Programs (Figure 12.13 of the book):
//
//   (flex/SP  ((I T)*) Ebody Ddefn*)    D ∈ def | def (I T ... ) | def-datatype
//
// The kernel program form (flexk/SP ((I T)*) Ebody) is accepted as a
// permissive superset, mirroring FLEX's flexk form.
//
// The list keywords (cons, car, cdr, null, null?) name the polymorphic
// standard-library procedures in a bare value position (e.g. (pcall cons
// int)), while their list forms remain the (permissive) monomorphic kernel
// constructs: (cons h t), (car e), ..., (null T).
//
// Type positions are parsed by parseType, which is DSL.flex.T.parse plus
// the (forall (τ*) T) form (FLEX itself stays forall-free: T.parse has no
// forall case, so FLEX and FLEX/S behavior is unchanged).

object FlexSPProgram extends FlLexer {

    // All FLEX/SP keywords (kernel + sugar + program), per Figures 11.31
    // and 12.13.
    private val keywords = Set(
        // program keywords
        "flex/SP", "flexk/SP",
        // kernel expression keywords
        "error", "if", "prim", "abs", "let", "letrec", "the", "sym",
        "pair", "fst", "snd", "prod", "get",
        "seq", "seq-get", "seq-size",
        "record", "select", "with",
        "one", "tagcase",
        "cons", "car", "cdr", "null", "null?",
        "set!", "cell", "^", ":=", "cell=?",
        "pabs", "pcall",
        // sugar keywords
        "cond", "def", "def-type", "def-datatype", "else", "let-type",
        "let-type*", "scand", "scor", "list", "begin")

    // The list keywords that also name FLEX/SP standard-library procedures
    // in a bare value position (book p.728: the standard list procedures
    // become polymorphic values in FLEX/SP).
    private val bareValueKeywords = Set("cons", "car", "cdr", "null", "null?")

    def apply(input: String): Option[FlexPgm] = {
        parse(sExp, input) match {
            case Success(raw, _) => interpretProgram(raw)
            case _ => None
        }
    }

    def interpretProgram(raw: Raw): Option[FlexPgm] = raw match {
        case RawList(List(RawAtom("flexk/SP"), formalsRaw, bodyRaw)) =>
            for {
                fs <- typedFormals(formalsRaw)
                body <- interpret(bodyRaw)
            } yield FlexKernelProgram(fs, body)
        case RawList(List(RawAtom("flex/SP"), formalsRaw, bodyRaw, items @ _*)) =>
            for {
                fs <- typedFormals(formalsRaw)
                (typeDefs, defs) <- interpretSPItems(items.toList)
                body <- interpret(bodyRaw)
            } yield FlexSugarProgram(fs, body, typeDefs, defs)
        case _ => None
    }

    // ------------------------------------------------------------------
    // Types: DSL.flex.T.parseForall — DSL.flex.T.parse plus the
    // (forall (τ*) T) form at every nesting position (FLEX itself stays
    // forall-free: T.parse has no forall case).
    // ------------------------------------------------------------------

    def parseType(raw: Raw): Option[T] = DSL.flex.T.parseForall(raw)

    // (I1 ... In) — the binder list of a (pabs (I*) E) expression: a
    // nonempty, duplicate-free list of type identifiers (Figure 12.9).
    private def typeVars(raw: Raw): Option[List[String]] = raw match {
        case RawList(items) if items.nonEmpty =>
            val vs: List[Option[String]] = items.map {
                case RawAtom(n) if validTypeIdent(n) => Some(n)
                case _ => None
            }
            if (vs.exists(_.isEmpty) || vs.map(_.get).toSet.size != vs.size) None
            else Some(vs.map(_.get))
        case _ => None
    }

    // ------------------------------------------------------------------
    // Expressions
    // ------------------------------------------------------------------

    def interpret(raw: Raw): Option[Exp] = raw match {
        case RawAtom(a) => interpretAtom(a)
        case RawList(items) => interpretList(items)
    }

    // A value position: a literal, a value identifier (which may not be a
    // keyword), or one of the list keywords naming a standard-library
    // procedure.
    def interpretAtom(a: String): Option[Exp] = {
        if (bareValueKeywords.contains(a)) Some(Var(a))
        else if (keywords.contains(a)) None
        else Some(a match {
            case "#u" => UnitLit()
            case "#t" => BoolLit(true)
            case "#f" => BoolLit(false)
            case n if isInt(n) => IntLit(n.toInt)
            case other => Var(other)
        })
    }

    private def isInt(s: String): Boolean = {
        val digits = if (s.nonEmpty && s.head == '-') s.tail else s
        digits.nonEmpty && digits.forall(_.isDigit)
    }

    def interpretList(items: List[Raw]): Option[Exp] = items match {
        case Nil => None
        case RawAtom(k) :: rest if keywords.contains(k) => interpretKeyword(k, rest)
        case RawAtom(a) :: rest if a.startsWith("@") =>
            allOf(rest.map(interpret)) map (args => SugaredPrimOp(a.drop(1), args))
        case first :: rest =>
            for {
                rator <- interpret(first)
                args <- allOf(rest.map(interpret))
            } yield AppExp(rator, args)
    }

    def interpretKeyword(k: String, rest: List[Raw]): Option[Exp] = k match {
        // Kernel forms (Figure 11.31 + the FLEX/SP forms of Figure 12.9).
        case "error" => rest match {
            case List(RawAtom(msg), tRaw) => parseType(tRaw) map (FlexError(msg, _))
            case _ => None
        }
        case "if" => rest match {
            case List(t, th, el) => lift3(interpret(t), interpret(th), interpret(el)) (If(_, _, _))
            case _ => None
        }
        case "prim" => rest match {
            case List(RawAtom(opName), args @ _*) =>
                for {
                    tag <- PrimOpTag.fromName(opName)
                    a <- allOf(args.toList.map(interpret))
                } yield PrimOp(tag, a)
            case _ => None
        }
        case "abs" => rest match {
            case List(formalsRaw, body) =>
                for {
                    fs <- typedFormals(formalsRaw)
                    b <- interpret(body)
                } yield AbsExp(fs, b)
            case _ => None
        }
        // let is a kernel form in FLEX (book p.632): bindings are untyped.
        case "let" => rest match {
            case List(bindsRaw, body) =>
                for {
                    bs <- untypedBindings(bindsRaw)
                    b <- interpret(body)
                } yield Let(bs, b)
            case _ => None
        }
        case "letrec" => rest match {
            case List(bindsRaw, body) =>
                for {
                    bs <- typedBindings(bindsRaw)
                    b <- interpret(body)
                } yield LetRecExp(bs, b)
            case _ => None
        }
        case "the" => rest match {
            case List(tRaw, e) =>
                for {
                    t <- parseType(tRaw)
                    ex <- interpret(e)
                } yield TheExp(t, ex)
            case _ => None
        }
        case "sym" => rest match {
            case List(RawAtom(s)) => Some(Sym(s))
            case _ => None
        }
        case "pair" => rest match {
            case List(f, s) => lift2(interpret(f), interpret(s)) (Pair(_, _))
            case _ => None
        }
        case "fst" => unary(rest) (FstExp(_))
        case "snd" => unary(rest) (SndExp(_))
        case "prod" => allOf(rest.map(interpret)) map (cs => ProdExp(cs))
        case "get" => rest match {
            // The index must be an integer literal (Figure 11.16).
            case List(RawAtom(n), e) if isInt(n) =>
                interpret(e) map (GetExp(n.toInt, _))
            case _ => None
        }
        case "seq" => allOf(rest.map(interpret)) map (cs => SeqExp(cs))
        case "seq-get" => rest match {
            case List(i, s) => lift2(interpret(i), interpret(s)) (SeqGetExp(_, _))
            case _ => None
        }
        case "seq-size" => unary(rest) (SeqSizeExp(_))
        case "record" => recordFields(rest) map (fs => RecordExp(fs))
        case "select" => rest match {
            case List(nameRaw, e) =>
                for {
                    n <- selectName(nameRaw)
                    ex <- interpret(e)
                } yield SelectExp(n, ex)
            case _ => None
        }
        case "with" => rest match {
            case List(rcd, body) => lift2(interpret(rcd), interpret(body)) (WithExp(_, _))
            case _ => None
        }
        case "one" => rest match {
            case List(tRaw, tagRaw, payload) =>
                for {
                    t <- parseType(tRaw)
                    tag <- selectName(tagRaw)
                    p <- interpret(payload)
                } yield OneExp(t, tag, p)
            case _ => None
        }
        case "tagcase" => rest match {
            case List(discRaw, payloadRaw, clauses @ _*) =>
                // A trailing (else E) clause is optional (Figure 11.22).
                val (clausesRaw, elseRaw) = clauses.toList match {
                    case Nil => (Nil, None)
                    case init2 :+ last if isElse(last) => (init2, Some(last))
                    case cs => (cs, None)
                }
                val parsedElse: Option[Option[Exp]] = elseRaw match {
                    case Some(raw) => elseBody(raw) map (Some(_))
                    case None => Some(None)
                }
                for {
                    d <- interpret(discRaw)
                    pn <- selectName(payloadRaw)
                    cs <- allOf(clausesRaw.map(tagClause))
                    el <- parsedElse
                } yield TagCaseExp(d, pn, cs, el)
            case _ => None
        }
        case "cons" => rest match {
            case List(h, t) => lift2(interpret(h), interpret(t)) (ConsExp(_, _))
            case _ => None
        }
        case "car" => unary(rest) (CarExp(_))
        case "cdr" => unary(rest) (CdrExp(_))
        case "null" => rest match {
            case List(tRaw) => parseType(tRaw) map (t => NullExp(t))
            case _ => None
        }
        case "null?" => unary(rest) (NullQExp(_))
        case "set!" => rest match {
            case List(nameRaw, e) =>
                for {
                    n <- selectName(nameRaw)
                    ex <- interpret(e)
                } yield SetExp(n, ex)
            case _ => None
        }
        case "cell" => unary(rest) (CellExp(_))
        case "^" => unary(rest) (DerefExp(_))
        case ":=" => rest match {
            case List(c, e) => lift2(interpret(c), interpret(e)) (CellSetExp(_, _))
            case _ => None
        }
        case "cell=?" => rest match {
            case List(e1, e2) => lift2(interpret(e1), interpret(e2)) (CellEqExp(_, _))
            case _ => None
        }

        // FLEX/SP kernel forms (Figure 12.9).
        case "pabs" => rest match {
            case List(varsRaw, body) =>
                typeVars(varsRaw) flatMap { vs =>
                    interpret(body) map (PabsExp(vs, _))
                }
            case _ => None
        }
        case "pcall" => rest match {
            case List(eRaw, ts @ _*) =>
                for {
                    e <- interpret(eRaw)
                    ts2 <- allOf(ts.toList.map(parseType))
                } yield PcallExp(e, ts2)
            case _ => None
        }

        // Sugar forms (Figures 11.2, 11.21, and 11.24).
        case "cond" => interpretCond(rest)
        case "scand" => allOf(rest.map(interpret)) map (es => Scand(es))
        case "scor" => allOf(rest.map(interpret)) map (es => Scor(es))
        case "begin" => rest match {
            case List(e1, e2) => lift2(interpret(e1), interpret(e2)) (BeginExp(_, _))
            case _ => None
        }
        case "let-type" => rest match {
            case List(bindsRaw, body) =>
                for {
                    bs <- typeBindings(bindsRaw)
                    b <- interpret(body)
                } yield LetTypeExp(bs, b)
            case _ => None
        }
        case "let-type*" => rest match {
            case List(bindsRaw, body) =>
                for {
                    bs <- typeBindings(bindsRaw)
                    b <- interpret(body)
                } yield LetTypeStarExp(bs, b)
            case _ => None
        }
        case "list" => rest match {
            // (list T E*) — the element type is explicit (Figure 11.24).
            case List(tRaw, es @ _*) =>
                for {
                    t <- parseType(tRaw)
                    els <- allOf(es.toList.map(interpret))
                } yield ListExp(t, els)
            case _ => None
        }
        case _ => None
    }

    private def isElse(raw: Raw): Boolean = raw match {
        case RawList(List(RawAtom("else"), _)) => true
        case _ => false
    }

    private def elseBody(raw: Raw): Option[Exp] = raw match {
        case RawList(List(RawAtom("else"), e)) => interpret(e)
        case _ => None
    }

    private def tagClause(raw: Raw): Option[(String, Exp)] = raw match {
        case RawList(List(tagRaw, body)) =>
            for {
                tag <- selectName(tagRaw)
                b <- interpret(body)
            } yield (tag, b)
        case _ => None
    }

    def interpretCond(items: List[Raw]): Option[Exp] = {
        val branches = List.newBuilder[(Exp, Exp)]
        var default: Option[Exp] = None
        var err: Option[String] = None
        items.foreach {
            case RawList(List(RawAtom("else"), d)) if default.isEmpty =>
                interpret(d) match {
                    case Some(e) => default = Some(e)
                    case None => err = Some("cond: malformed else clause")
                }
            case RawList(List(t, th)) =>
                (interpret(t), interpret(th)) match {
                    case (Some(te), Some(ee)) => branches += ((te, ee))
                    case _ => err = Some("cond: malformed branch")
                }
            case _ => err = Some("cond: malformed clause")
        }
        err match {
            case Some(_) => None
            case None => Some(Cond(branches.result(), default))
        }
    }

    // ------------------------------------------------------------------
    // Binding lists and formals
    // ------------------------------------------------------------------

    // ((I T)*) — typed formals (program parameters, abs parameters).
    def typedFormals(raw: Raw): Option[List[(String, T)]] = raw match {
        case RawList(items) =>
            allOf(items.map {
                case RawList(List(RawAtom(name), tRaw)) if validIdent(name) =>
                    parseType(tRaw) map (t => name -> t)
                case _ => None
            })
        case _ => None
    }

    // ((I E)*) — untyped let bindings (the FLEX kernel let, book p.632).
    def untypedBindings(raw: Raw): Option[List[(String, Exp)]] = raw match {
        case RawList(items) =>
            allOf(items.map {
                case RawList(List(RawAtom(name), e)) if validIdent(name) =>
                    interpret(e) map (ex => name -> ex)
                case _ => None
            })
        case _ => None
    }

    // ((I T E)*) — typed letrec bindings.
    def typedBindings(raw: Raw): Option[List[(String, T, Exp)]] = raw match {
        case RawList(items) =>
            allOf(items.map {
                case RawList(List(RawAtom(name), tRaw, e)) if validIdent(name) =>
                    (parseType(tRaw), interpret(e)) match {
                        case (Some(t), Some(ex)) => Some((name, t, ex))
                        case _ => None
                    }
                case _ => None
            })
        case _ => None
    }

    // ((tau T)*) — type bindings for let-type / let-type* / def-type bodies.
    def typeBindings(raw: Raw): Option[List[(String, T)]] = raw match {
        case RawList(items) =>
            allOf(items.map {
                case RawList(List(RawAtom(name), tRaw)) if validTypeIdent(name) =>
                    parseType(tRaw) map (t => name -> t)
                case _ => None
            })
        case _ => None
    }

    private def recordFields(raws: List[Raw]): Option[List[(String, Exp)]] =
        allOf(raws.map {
            case RawList(List(RawAtom(name), e)) if validIdent(name) =>
                interpret(e) map (ex => name -> ex)
            case _ => None
        })

    // A value-identifier position: a name that is not a keyword.
    private def selectName(raw: Raw): Option[String] = raw match {
        case RawAtom(n) if validIdent(n) => Some(n)
        case _ => None
    }

    private def validIdent(name: String): Boolean =
        !name.startsWith("@") && !keywords.contains(name)

    private def validTypeIdent(name: String): Boolean =
        !name.startsWith("@") && !T.TypeKeywords.contains(name)

    // ------------------------------------------------------------------
    // Program items of a flex/SP program (Figure 12.13): def-type / def /
    // def-datatype in any order, normalized to (all def-types first, then
    // all defs), preserving relative order (the figure's footnote).
    // ------------------------------------------------------------------

    def interpretSPItems(items: List[Raw]): Option[(List[(String, T)], List[FlexDef])] = {
        val typeDefs = List.newBuilder[(String, T)]
        val defs = List.newBuilder[FlexDef]
        var err: Option[String] = None
        items.foreach {
            case RawList(List(RawAtom("def-type"), RawAtom(name), tRaw)) if err.isEmpty =>
                if (!validTypeIdent(name)) err = Some(s"illegal type identifier: $name")
                else parseType(tRaw) match {
                    case Some(t) => typeDefs += (name -> t)
                    case None => err = Some(s"malformed type in def-type: $name")
                }
            case RawList(List(RawAtom("def-datatype"), RawAtom(name), clauses @ _*)) if err.isEmpty =>
                if (!validTypeIdent(name)) err = Some(s"illegal type identifier: $name")
                else interpretDataTypeClauses(name, clauses.toList) match {
                    case Some((td, ctors, dctrs)) =>
                        typeDefs += td
                        ctors.foreach(d => defs += d)
                        dctrs.foreach(d => defs += d)
                    case None => err = Some(s"malformed def-datatype: $name")
                }
            case item @ RawList(List(RawAtom("def"), _*)) if err.isEmpty =>
                interpretDef(item) match {
                    case Some(d) => defs += d
                    case None => err = Some("malformed def")
                }
            case _ if err.isEmpty =>
                err = Some("malformed program item")
            case _ => ()
        }
        err match {
            case Some(_) => None
            case None => Some((typeDefs.result(), defs.result()))
        }
    }

    // The desugaring of Figure 12.13 applied to one def-datatype:
    //
    //   (def-datatype τdata (Itag1 T1*) ... (Itagn Tn*))
    //   =>
    //   (def-type τdata (trec τdata (oneof (Itag1 (prodof T1*)) ... (Itagn (prodof Tn*)))))
    //   (def Itag1 (-> (T1* τdata)) (abs ((x1 T1*) ...) (one τdata Itag1 (prod x1 ...))))
    //   (def Itag1~ (forall (τret) (-> (τdata (-> (T1*) τret) (-> () τret)) τret))
    //     (pabs (τret) (abs ((val τdata) (succ (-> (T1*) τret)) (fail (-> () τret)))
    //       (tagcase val payload (Itag1 (succ (get 1 payload) ...)) (else (fail))))))
    //   ...
    //
    // returning (the def-type, the constructor defs, the deconstructor defs).
    private def interpretDataTypeClauses(name: String, clauses: List[Raw])
                                        : Option[( (String, T), List[FlexDef], List[FlexDef])] =
        allOf(clauses.map(dataTypeClause)) map { cs =>
            val td = (name, TTrec(name, TOneof(cs.map { case (tag, ts) => (tag, TProd(ts)) })))
            val ctors = cs.map { case (tag, ts) =>
                val xs = (1 to ts.size).map(i => "x" + i).toList
                FlexDef(tag, TArrow(ts, TVar(name)),
                        AbsExp(xs.zip(ts), OneExp(TVar(name), tag, ProdExp(xs.map(Var(_))))))
            }
            val dctrs = cs.map { case (tag, ts) =>
                deconstructorDef(name, tag, ts)
            }
            (td, ctors, dctrs)
        }

    private def deconstructorDef(data: String, tag: String, ts: List[T]): FlexDef = {
        val ret = "t_ret"
        FlexDef(tag + "~",
            TForall(List(ret),
                TArrow(List(TVar(data), TArrow(ts, TVar(ret)), TArrow(Nil, TVar(ret))), TVar(ret))),
            PabsExp(List(ret),
                AbsExp(List(("val", TVar(data)),
                            ("succ", TArrow(ts, TVar(ret))),
                            ("fail", TArrow(Nil, TVar(ret)))),
                    TagCaseExp(Var("val"), "payload",
                               List((tag, AppExp(Var("succ"),
                                                (1 to ts.size).map(i => GetExp(i, Var("payload"))).toList))),
                               Some(AppExp(Var("fail"), Nil))))))
    }

    private def dataTypeClause(raw: Raw): Option[(String, List[T])] = raw match {
        case RawList(RawAtom(tag) :: tsRaw) if validIdent(tag) =>
            allOf(tsRaw.map(parseType)) map (ts => tag -> ts)
        case _ => None
    }

    // (def I T E) or the procedure-defining sugar
    // (def (Iproc Treturn (I1 T1) ... (In Tn)) Ebody) — the formal pairs are
    // direct elements of the head list (book p.636), converted at parse time
    // to (def I (-> (T1 ... Tn) Treturn) (abs ((I1 T1) ... (In Tn)) Ebody)).
    def interpretDef(raw: Raw): Option[FlexDef] = raw match {
        case RawList(List(RawAtom("def"), RawAtom(name), tRaw, e)) =>
            for {
                _ <- if (validIdent(name)) Some(()) else None
                t <- parseType(tRaw)
                ex <- interpret(e)
            } yield FlexDef(name, t, ex)
        case RawList(List(RawAtom("def"), RawList(List(RawAtom(name), tRetRaw, formals @ _*)), e)) =>
            for {
                _ <- if (validIdent(name)) Some(()) else None
                tRet <- parseType(tRetRaw)
                params <- allOf(formals.toList.map {
                    case RawList(List(RawAtom(n), tRaw2)) if validIdent(n) =>
                        parseType(tRaw2) map (t => n -> t)
                    case _ => None
                })
                ex <- interpret(e)
            } yield FlexDef(name, TArrow(params.map(_._2), tRet), AbsExp(params, ex))
        case _ => None
    }

    // ------------------------------------------------------------------
    // Option combinators
    // ------------------------------------------------------------------

    private def allOf[A](oas: List[Option[A]]): Option[List[A]] =
        oas.foldRight[Option[List[A]]](Some(Nil)) { (oa, acc) =>
            acc flatMap { as => oa map (_ +: as) }
        }

    private def lift2[A, B, C](oa: Option[A], ob: Option[B])(f: (A, B) => C): Option[C] =
        for {
            a <- oa
            b <- ob
        } yield f(a, b)

    private def lift3[A, B, C, D](oa: Option[A], ob: Option[B], oc: Option[C])(f: (A, B, C) => D): Option[D] =
        for {
            a <- oa
            b <- ob
            c <- oc
        } yield f(a, b, c)

    private def unary(rest: List[Raw])(f: Exp => Exp): Option[Exp] = rest match {
        case List(e) => interpret(e) map f
        case _ => None
    }
}
