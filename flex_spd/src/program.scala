package DSL.flex_spd

import DSL.fl._
import DSL.flex._
import DSL.flex_sp._
import scala.util.parsing.combinator._

// Parses FLEX/SPD concrete syntax (s-expressions) into the FLEX/SPD AST.
//
// FLEX/SPD (Section 12.3.1 of the book) is FLEX/SP in which every type
// annotation is a *description* (Figure 12.18). A description is either a
// type (with τ replaced by the description identifier δ) or one of
//
//   cellof | seqof             base type constructors (1-arg operators)
//   (dabs (δ*) D)              a description abstraction (type constructor)
//   (Drator Drand*)            a description application
//   (dletrec ((δ D)*) D)       a (mutually) recursive description
//
// plus the sugar
//
//   (dlet ((δ D)*) D)   ~  [D/δ]* D         (parse-time substitution)
//   (drec δ D)          ~  (dletrec ((δ D)) δ)
//   (plet    ((δ D)*) E)                    (expression-level, checked)
//   (pletrec ((δ D)*) E)                    (expression-level, checked)
//
// Per Figure 12.18, the FLEX/SP type keywords cellof, listof, pairof, seqof,
// trec, and tletrec are NOT description keywords: cellof / seqof become base
// type constructors (used as application rators, e.g. (seqof int)), listof
// and pairof become standard-library description identifiers (Figure 12.19),
// and trec / tletrec are replaced by drec / dletrec. The pair and list
// *expression* forms (pair, fst, snd, cons, car, cdr, null, null?) are not
// part of the FLEX/SPD kernel either: they are replaced by polymorphic
// standard-library values (book p.755, Figure 12.19), so those keywords name
// standard-library values in a bare value position (like in FLEX/SP). The
// let-type / let-type* and list sugars are replaced by plet / pletrec and
// the standard-library values, and the def-type program item is accepted as
// an alias of def-desc (a type is a description).
//
// Programs (Figure 12.18 / Figure 12.19 of the book):
//
//   (flexk/SPD ((I D)*) Ebody)
//   (flex/SPD  ((I D)*) Ebody (def-desc δ D)* (def I D E)*)
//
// where all def-desc items (including the ones generated by def-datatype)
// must precede all def items. A flex/SPD program desugars (Figure 12.19) to
// a flexk/SPD program whose body is wrapped in: the standard-library
// descriptions (pairof, listof), the standard-library values (the list /
// pair procedures and the primops), a pletrec binding the program's
// def-desc descriptions, and a letrec binding the program's value
// definitions. The def-datatype item (inherited from FLEX/SP, Figure 12.13)
// desugars, at parse time, to a def-desc (a dletrec-based recursive
// description) and, for each clause, a constructor def and a polymorphic
// deconstructor def.

object FlexSPDProgram extends FlLexer {

    // All FLEX/SPD keywords in value position: the program tags, the kernel
    // expression keywords (the FLEX/SP ones, minus the list / pair expression
    // forms of Figures 11.15 and 11.24, which FLEX/SPD replaces with
    // standard-library values), and the sugar keywords. The description
    // keywords (->, oneof, prodof, recordof, forall, dabs, dletrec, and the
    // base types / base type constructors) are recognized only in description
    // positions (by parseDesc / DescEval), not in value positions.
    private val keywords = Set(
        // program keywords
        "flex/SPD", "flexk/SPD",
        // kernel expression keywords
        "error", "if", "prim", "abs", "let", "letrec", "the", "sym",
        "prod", "get",
        "seq", "seq-get", "seq-size",
        "record", "select", "with",
        "one", "tagcase",
        "set!", "cell", "^", ":=", "cell=?",
        "pabs", "pcall",
        // sugar keywords
        "cond", "def", "def-desc", "def-type", "def-datatype", "else",
        "plet", "pletrec", "scand", "scor", "begin", "dlet", "drec")

    // The keywords that also name FLEX/SPD standard-library procedures in a
    // bare value position (book p.755 and Figure 12.19: the list and pair
    // operations become polymorphic standard-library values).
    private val bareValueKeywords = Set("cons", "car", "cdr", "null", "null?",
                                        "pair", "fst", "snd")

    def apply(input: String): Option[FlexSPDPgm] = {
        parse(sExp, input) match {
            case Success(raw, _) => interpretProgram(raw)
            case _ => None
        }
    }

    def interpretProgram(raw: Raw): Option[FlexSPDPgm] = raw match {
        case RawList(List(RawAtom("flexk/SPD"), formalsRaw, bodyRaw)) =>
            for {
                fs <- typedFormals(formalsRaw)
                body <- interpret(bodyRaw)
            } yield FlexSPDKernel(fs, body)
        case RawList(List(RawAtom("flex/SPD"), formalsRaw, bodyRaw, items @ _*)) =>
            for {
                fs <- typedFormals(formalsRaw)
                (descDefs, defs) <- interpretItems(items.toList)
                body <- interpret(bodyRaw)
            } yield FlexSPDSugar(fs, body, descDefs, defs)
        case _ => None
    }

    // ------------------------------------------------------------------
    // Descriptions (Figure 12.18)
    // ------------------------------------------------------------------

    // Parse a description: a base type, a base type constructor, a
    // description identifier, or one of the kernel / sugar description
    // forms. A list whose head is not a description keyword is a description
    // application (Drator Drand*); the rator may be an atom (a base type
    // constructor or a description identifier) or a nested parenthesized
    // description (the book's example ((dabs (t) (prodof t t)) int), p.753).
    // A base type in rator position parses (e.g. (int bool)) and is rejected
    // at check time (the book's "safe nonsense", p.757).
    def parseDesc(raw: Raw): Option[T] = raw match {
        case RawAtom(a) =>
            if (T.BaseTypeNames.contains(a)) Some(TBase(a))
            else if (DescEval.BaseTypeConstructors.contains(a)) Some(TBaseCtor(a))
            else if (DescEval.DescKeywords.contains(a)) None // a keyword is not a description identifier
            else Some(TVar(a))
        case RawList(items) => items match {
            case List(RawAtom("->"), argsRaw, retRaw) =>
                parseDescList(argsRaw) flatMap { args =>
                    parseDesc(retRaw) map (ret => TArrow(args, ret)) }
            case List(RawAtom("oneof"), assocs @ _*) =>
                parseDescAssocs(assocs.toList) map (ts => TOneof(ts))
            case List(RawAtom("prodof"), ts @ _*) =>
                allOf(ts.toList.map(parseDesc)) map (cs => TProd(cs))
            case List(RawAtom("recordof"), assocs @ _*) =>
                parseDescAssocs(assocs.toList) map (fs => TRecord(fs))
            case List(RawAtom("forall"), varsRaw, bodyRaw) =>
                descVars(varsRaw) flatMap { vs =>
                    parseDesc(bodyRaw) map (b => TForall(vs, b)) }
            case List(RawAtom("dabs"), varsRaw, bodyRaw) =>
                descVars(varsRaw) flatMap { vs =>
                    parseDesc(bodyRaw) map (b => TDabs(vs, b)) }
            case List(RawAtom("dletrec"), bindsRaw, bodyRaw) =>
                descBindings(bindsRaw) flatMap { bs =>
                    parseDesc(bodyRaw) map (b => TDletrec(bs, b)) }
            // Sugar: dlet — name descriptions within a description; desugars
            // at parse time to a description substitution (Figure 12.18).
            case List(RawAtom("dlet"), bindsRaw, bodyRaw) =>
                (descBindings(bindsRaw), parseDesc(bodyRaw)) match {
                    case (Some(bs), Some(b)) => Some(Subst.substSim(bs, b))
                    case _ => None
                }
            // Sugar: drec — (dletrec ((δ D)) δ) (Figure 12.18).
            case List(RawAtom("drec"), RawAtom(name), bodyRaw) =>
                if (validDescIdent(name))
                    parseDesc(bodyRaw) map (b => TDletrec(List(name -> b), TVar(name)))
                else None
            // A description application: (Drator Drand*). An empty list is
            // not a description.
            case head :: rest if rest.nonEmpty =>
                for {
                    rator <- parseDesc(head)
                    args <- allOf(rest.map(parseDesc))
                } yield TDApp(rator, args)
            case _ => None
        }
    }

    // (D1 ... Dn) — a list of descriptions (the arrow's argument list).
    private def parseDescList(raw: Raw): Option[List[T]] = raw match {
        case RawList(items) => allOf(items.map(parseDesc))
        case _ => None
    }

    // ((I D)*) — the associations of an oneof / recordof description: a
    // value identifier (a tag or field name) and a description.
    private def parseDescAssocs(raws: List[Raw]): Option[List[(String, T)]] =
        allOf(raws.map {
            case RawList(List(RawAtom(n), dRaw)) if validIdent(n) =>
                parseDesc(dRaw) map (d => n -> d)
            case _ => None
        })

    // (δ1 ... δn) — a nonempty, duplicate-free list of description
    // identifiers (the binder list of a forall / dabs).
    private def descVars(raw: Raw): Option[List[String]] = raw match {
        case RawList(items) if items.nonEmpty =>
            val vs: List[Option[String]] = items.map {
                case RawAtom(n) if validDescIdent(n) => Some(n)
                case _ => None
            }
            if (vs.exists(_.isEmpty) || vs.map(_.get).toSet.size != vs.size) None
            else Some(vs.map(_.get))
        case _ => None
    }

    // ((δ D)*) — description bindings (dletrec / plet / pletrec / dlet).
    private def descBindings(raw: Raw): Option[List[(String, T)]] = raw match {
        case RawList(items) =>
            allOf(items.map {
                case RawList(List(RawAtom(name), dRaw)) if validDescIdent(name) =>
                    parseDesc(dRaw) map (d => name -> d)
                case _ => None
            })
        case _ => None
    }

    // ------------------------------------------------------------------
    // Expressions
    // ------------------------------------------------------------------

    def interpret(raw: Raw): Option[Exp] = raw match {
        case RawAtom(a) => interpretAtom(a)
        case RawList(items) => interpretList(items)
    }

    // A value position: a literal, a value identifier (which may not be a
    // keyword), or one of the list / pair keywords naming a standard-library
    // procedure.
    def interpretAtom(a: String): Option[Exp] = {
        if (bareValueKeywords.contains(a)) Some(Var(a))
        else if (keywords.contains(a)) None
        else Some(a match {
            case "#u" => UnitLit()
            case "#t" => BoolLit(true)
            case "#f" => BoolLit(false)
            case n if isInt(n) => IntLit(n.toInt)
            case other => Var(other)
        })
    }

    private def isInt(s: String): Boolean = {
        val digits = if (s.nonEmpty && s.head == '-') s.tail else s
        digits.nonEmpty && digits.forall(_.isDigit)
    }

    def interpretList(items: List[Raw]): Option[Exp] = items match {
        case Nil => None
        case RawAtom(k) :: rest if keywords.contains(k) => interpretKeyword(k, rest)
        case RawAtom(a) :: rest if a.startsWith("@") =>
            allOf(rest.map(interpret)) map (args => SugaredPrimOp(a.drop(1), args))
        case first :: rest =>
            for {
                rator <- interpret(first)
                args <- allOf(rest.map(interpret))
            } yield AppExp(rator, args)
    }

    def interpretKeyword(k: String, rest: List[Raw]): Option[Exp] = k match {
        // Kernel forms (Figure 12.18: the FLEX/SP expressions, minus the
        // list / pair forms, with T replaced by D in every type position).
        case "error" => rest match {
            case List(RawAtom(msg), dRaw) => parseDesc(dRaw) map (FlexError(msg, _))
            case _ => None
        }
        case "if" => rest match {
            case List(t, th, el) => lift3(interpret(t), interpret(th), interpret(el)) (If(_, _, _))
            case _ => None
        }
        case "prim" => rest match {
            case List(RawAtom(opName), args @ _*) =>
                for {
                    tag <- PrimOpTag.fromName(opName)
                    a <- allOf(args.toList.map(interpret))
                } yield PrimOp(tag, a)
            case _ => None
        }
        case "abs" => rest match {
            case List(formalsRaw, body) =>
                for {
                    fs <- typedFormals(formalsRaw)
                    b <- interpret(body)
                } yield AbsExp(fs, b)
            case _ => None
        }
        // let is a kernel form in FLEX (book p.632): bindings are untyped.
        case "let" => rest match {
            case List(bindsRaw, body) =>
                for {
                    bs <- untypedBindings(bindsRaw)
                    b <- interpret(body)
                } yield Let(bs, b)
            case _ => None
        }
        case "letrec" => rest match {
            case List(bindsRaw, body) =>
                for {
                    bs <- typedBindings(bindsRaw)
                    b <- interpret(body)
                } yield LetRecExp(bs, b)
            case _ => None
        }
        case "the" => rest match {
            case List(dRaw, e) =>
                for {
                    d <- parseDesc(dRaw)
                    ex <- interpret(e)
                } yield TheExp(d, ex)
            case _ => None
        }
        case "sym" => rest match {
            case List(RawAtom(s)) => Some(Sym(s))
            case _ => None
        }
        case "prod" => allOf(rest.map(interpret)) map (cs => ProdExp(cs))
        case "get" => rest match {
            // The index must be an integer literal (Figure 11.16).
            case List(RawAtom(n), e) if isInt(n) =>
                interpret(e) map (GetExp(n.toInt, _))
            case _ => None
        }
        case "seq" => allOf(rest.map(interpret)) map (cs => SeqExp(cs))
        case "seq-get" => rest match {
            case List(i, s) => lift2(interpret(i), interpret(s)) (SeqGetExp(_, _))
            case _ => None
        }
        case "seq-size" => unary(rest) (SeqSizeExp(_))
        case "record" => recordFields(rest) map (fs => RecordExp(fs))
        case "select" => rest match {
            case List(nameRaw, e) =>
                for {
                    n <- selectName(nameRaw)
                    ex <- interpret(e)
                } yield SelectExp(n, ex)
            case _ => None
        }
        case "with" => rest match {
            case List(rcd, body) => lift2(interpret(rcd), interpret(body)) (WithExp(_, _))
            case _ => None
        }
        case "one" => rest match {
            case List(dRaw, tagRaw, payload) =>
                for {
                    d <- parseDesc(dRaw)
                    tag <- selectName(tagRaw)
                    p <- interpret(payload)
                } yield OneExp(d, tag, p)
            case _ => None
        }
        case "tagcase" => rest match {
            case List(discRaw, payloadRaw, clauses @ _*) =>
                // A trailing (else E) clause is optional (Figure 11.22).
                val (clausesRaw, elseRaw) = clauses.toList match {
                    case Nil => (Nil, None)
                    case init2 :+ last if isElse(last) => (init2, Some(last))
                    case cs => (cs, None)
                }
                val parsedElse: Option[Option[Exp]] = elseRaw match {
                    case Some(raw) => elseBody(raw) map (Some(_))
                    case None => Some(None)
                }
                for {
                    d <- interpret(discRaw)
                    pn <- selectName(payloadRaw)
                    cs <- allOf(clausesRaw.map(tagClause))
                    el <- parsedElse
                } yield TagCaseExp(d, pn, cs, el)
            case _ => None
        }
        case "set!" => rest match {
            case List(nameRaw, e) =>
                for {
                    n <- selectName(nameRaw)
                    ex <- interpret(e)
                } yield SetExp(n, ex)
            case _ => None
        }
        case "cell" => unary(rest) (CellExp(_))
        case "^" => unary(rest) (DerefExp(_))
        case ":=" => rest match {
            case List(c, e) => lift2(interpret(c), interpret(e)) (CellSetExp(_, _))
            case _ => None
        }
        case "cell=?" => rest match {
            case List(e1, e2) => lift2(interpret(e1), interpret(e2)) (CellEqExp(_, _))
            case _ => None
        }

        // FLEX/SP kernel forms (Figure 12.9).
        case "pabs" => rest match {
            case List(varsRaw, body) =>
                descVars(varsRaw) flatMap { vs =>
                    interpret(body) map (PabsExp(vs, _))
                }
            case _ => None
        }
        case "pcall" => rest match {
            case List(eRaw, ds @ _*) =>
                for {
                    e <- interpret(eRaw)
                    ds2 <- allOf(ds.toList.map(parseDesc))
                } yield PcallExp(e, ds2)
            case _ => None
        }

        // FLEX/SPD description bindings in expressions (Figure 12.18):
        // plet / pletrec bind descriptions in the body's type positions and
        // return a value. The bindings are transparent (a name is equivalent
        // to its definition); the checker realizes this by extending the
        // description environment (Figure 12.18's pletrec desugaring wraps
        // each binding in a dletrec over all the bindings).
        case "plet" => rest match {
            case List(bindsRaw, body) =>
                for {
                    bs <- descBindings(bindsRaw)
                    b <- interpret(body)
                } yield PletExp(bs, b)
            case _ => None
        }
        case "pletrec" => rest match {
            case List(bindsRaw, body) =>
                for {
                    bs <- descBindings(bindsRaw)
                    b <- interpret(body)
                } yield PletRecExp(bs, b)
            case _ => None
        }

        // Sugar forms (Figures 11.2 and 11.21).
        case "cond" => interpretCond(rest)
        case "scand" => allOf(rest.map(interpret)) map (es => Scand(es))
        case "scor" => allOf(rest.map(interpret)) map (es => Scor(es))
        case "begin" => rest match {
            case List(e1, e2) => lift2(interpret(e1), interpret(e2)) (BeginExp(_, _))
            case _ => None
        }
        case _ => None
    }

    private def isElse(raw: Raw): Boolean = raw match {
        case RawList(List(RawAtom("else"), _)) => true
        case _ => false
    }

    private def elseBody(raw: Raw): Option[Exp] = raw match {
        case RawList(List(RawAtom("else"), e)) => interpret(e)
        case _ => None
    }

    private def tagClause(raw: Raw): Option[(String, Exp)] = raw match {
        case RawList(List(tagRaw, body)) =>
            for {
                tag <- selectName(tagRaw)
                b <- interpret(body)
            } yield (tag, b)
        case _ => None
    }

    def interpretCond(items: List[Raw]): Option[Exp] = {
        val branches = List.newBuilder[(Exp, Exp)]
        var default: Option[Exp] = None
        var err: Option[String] = None
        items.foreach {
            case RawList(List(RawAtom("else"), d)) if default.isEmpty =>
                interpret(d) match {
                    case Some(e) => default = Some(e)
                    case None => err = Some("cond: malformed else clause")
                }
            case RawList(List(t, th)) =>
                (interpret(t), interpret(th)) match {
                    case (Some(te), Some(ee)) => branches += ((te, ee))
                    case _ => err = Some("cond: malformed branch")
                }
            case _ => err = Some("cond: malformed clause")
        }
        err match {
            case Some(_) => None
            case None => Some(Cond(branches.result(), default))
        }
    }

    // ------------------------------------------------------------------
    // Binding lists and formals
    // ------------------------------------------------------------------

    // ((I D)*) — typed formals (program parameters, abs parameters): a value
    // identifier and a description.
    def typedFormals(raw: Raw): Option[List[(String, T)]] = raw match {
        case RawList(items) =>
            allOf(items.map {
                case RawList(List(RawAtom(name), dRaw)) if validIdent(name) =>
                    parseDesc(dRaw) map (d => name -> d)
                case _ => None
            })
        case _ => None
    }

    // ((I E)*) — untyped let bindings (the FLEX kernel let, book p.632).
    def untypedBindings(raw: Raw): Option[List[(String, Exp)]] = raw match {
        case RawList(items) =>
            allOf(items.map {
                case RawList(List(RawAtom(name), e)) if validIdent(name) =>
                    interpret(e) map (ex => name -> ex)
                case _ => None
            })
        case _ => None
    }

    // ((I D E)*) — typed letrec bindings.
    def typedBindings(raw: Raw): Option[List[(String, T, Exp)]] = raw match {
        case RawList(items) =>
            allOf(items.map {
                case RawList(List(RawAtom(name), dRaw, e)) if validIdent(name) =>
                    (parseDesc(dRaw), interpret(e)) match {
                        case (Some(d), Some(ex)) => Some((name, d, ex))
                        case _ => None
                    }
                case _ => None
            })
        case _ => None
    }

    private def recordFields(raws: List[Raw]): Option[List[(String, Exp)]] =
        allOf(raws.map {
            case RawList(List(RawAtom(name), e)) if validIdent(name) =>
                interpret(e) map (ex => name -> ex)
            case _ => None
        })

    // A value-identifier position: a name that is not a keyword.
    private def selectName(raw: Raw): Option[String] = raw match {
        case RawAtom(n) if validIdent(n) => Some(n)
        case _ => None
    }

    private def validIdent(name: String): Boolean =
        !name.startsWith("@") && !keywords.contains(name)

    private def validDescIdent(name: String): Boolean =
        !name.startsWith("@") && !DescEval.DescKeywords.contains(name)

    // ------------------------------------------------------------------
    // Program items of a flex/SPD program (Figure 12.18): def-desc /
    // def-type / def-datatype / def in any order, normalized to (all
    // def-descs first, then all defs), preserving relative order (as in
    // FLEX/SP, Figure 12.13's footnote).
    // ------------------------------------------------------------------

    def interpretItems(items: List[Raw]): Option[(List[(String, T)], List[FlexDef])] = {
        val descDefs = List.newBuilder[(String, T)]
        val defs = List.newBuilder[FlexDef]
        var err: Option[String] = None
        items.foreach {
            case RawList(List(RawAtom("def-desc"), RawAtom(name), dRaw)) if err.isEmpty =>
                if (!validDescIdent(name)) err = Some(s"illegal description identifier: $name")
                else parseDesc(dRaw) match {
                    case Some(d) => descDefs += (name -> d)
                    case None => err = Some(s"malformed description in def-desc: $name")
                }
            case RawList(List(RawAtom("def-type"), RawAtom(name), dRaw)) if err.isEmpty =>
                // def-type is accepted as an alias of def-desc: a type is a
                // description (Figure 12.18 replaces def-type by def-desc).
                if (!validDescIdent(name)) err = Some(s"illegal description identifier: $name")
                else parseDesc(dRaw) match {
                    case Some(d) => descDefs += (name -> d)
                    case None => err = Some(s"malformed description in def-type: $name")
                }
            case RawList(List(RawAtom("def-datatype"), RawAtom(name), clauses @ _*)) if err.isEmpty =>
                if (!validDescIdent(name)) err = Some(s"illegal description identifier: $name")
                else interpretDataTypeClauses(name, clauses.toList) match {
                    case Some((dd, ctors, dctrs)) =>
                        descDefs += dd
                        ctors.foreach(d => defs += d)
                        dctrs.foreach(d => defs += d)
                    case None => err = Some(s"malformed def-datatype: $name")
                }
            case item @ RawList(List(RawAtom("def"), _*)) if err.isEmpty =>
                interpretDef(item) match {
                    case Some(d) => defs += d
                    case None => err = Some("malformed def")
                }
            case _ if err.isEmpty =>
                err = Some("malformed program item")
            case _ => ()
        }
        err match {
            case Some(_) => None
            case None => Some((descDefs.result(), defs.result()))
        }
    }

    // The desugaring of Figure 12.13 applied to one def-datatype, in the
    // FLEX/SPD description domain: the recursive data type is a def-desc
    // whose definition is a dletrec (the description analogue of the FLEX/SP
    // trec), and each clause yields a constructor def and a polymorphic
    // deconstructor def (Figure 12.11).
    //
    //   (def-datatype τdata (Itag1 T1*) ... (Itagn Tn*))
    //   =>
    //   (def-desc τdata (drec τdata (oneof (Itag1 (prodof T1*)) ... (Itagn (prodof Tn*)))))
    //   (def Itag1 (-> (T1* τdata)) (abs ((x1 T1*) ...) (one τdata Itag1 (prod x1 ...))))
    //   (def Itag1~ (forall (τret) (-> (τdata (-> (T1*) τret) (-> () τret)) τret))
    //     (pabs (τret) (abs ((val τdata) (succ (-> (T1*) τret)) (fail (-> () τret)))
    //       (tagcase val payload (Itag1 (succ (get 1 payload) ...)) (else (fail))))))
    //   ...
    //
    // returning (the def-desc, the constructor defs, the deconstructor defs).
    private def interpretDataTypeClauses(name: String, clauses: List[Raw])
                                        : Option[( (String, T), List[FlexDef], List[FlexDef])] =
        allOf(clauses.map(dataTypeClause)) map { cs =>
            val dd = (name, TDletrec(List(name -> TOneof(cs.map { case (tag, ts) => (tag, TProd(ts)) })),
                                     TVar(name)))
            val ctors = cs.map { case (tag, ts) =>
                val xs = (1 to ts.size).map(i => "x" + i).toList
                FlexDef(tag, TArrow(ts, TVar(name)),
                        AbsExp(xs.zip(ts), OneExp(TVar(name), tag, ProdExp(xs.map(Var(_))))))
            }
            val dctrs = cs.map { case (tag, ts) =>
                deconstructorDef(name, tag, ts)
            }
            (dd, ctors, dctrs)
        }

    private def deconstructorDef(data: String, tag: String, ts: List[T]): FlexDef = {
        val ret = "t_ret"
        FlexDef(tag + "~",
            TForall(List(ret),
                TArrow(List(TVar(data), TArrow(ts, TVar(ret)), TArrow(Nil, TVar(ret))), TVar(ret))),
            PabsExp(List(ret),
                AbsExp(List(("val", TVar(data)),
                            ("succ", TArrow(ts, TVar(ret))),
                            ("fail", TArrow(Nil, TVar(ret)))),
                    TagCaseExp(Var("val"), "payload",
                               List((tag, AppExp(Var("succ"),
                                                (1 to ts.size).map(i => GetExp(i, Var("payload"))).toList))),
                               Some(AppExp(Var("fail"), Nil))))))
    }

    private def dataTypeClause(raw: Raw): Option[(String, List[T])] = raw match {
        case RawList(RawAtom(tag) :: dsRaw) if validIdent(tag) =>
            allOf(dsRaw.map(parseDesc)) map (ds => tag -> ds)
        case _ => None
    }

    // (def I D E) or the procedure-defining sugar
    // (def (Iproc Dreturn (I1 D1) ... (In Dn)) Ebody) — the formal pairs are
    // direct elements of the head list (book p.636), converted at parse time
    // to (def I (-> (D1 ... Dn) Dreturn) (abs ((I1 D1) ... (In Dn)) Ebody)).
    def interpretDef(raw: Raw): Option[FlexDef] = raw match {
        case RawList(List(RawAtom("def"), RawAtom(name), dRaw, e)) =>
            for {
                _ <- if (validIdent(name)) Some(()) else None
                d <- parseDesc(dRaw)
                ex <- interpret(e)
            } yield FlexDef(name, d, ex)
        case RawList(List(RawAtom("def"), RawList(List(RawAtom(name), dRetRaw, formals @ _*)), e)) =>
            for {
                _ <- if (validIdent(name)) Some(()) else None
                dRet <- parseDesc(dRetRaw)
                params <- allOf(formals.toList.map {
                    case RawList(List(RawAtom(n), dRaw2)) if validIdent(n) =>
                        parseDesc(dRaw2) map (d => n -> d)
                    case _ => None
                })
                ex <- interpret(e)
            } yield FlexDef(name, TArrow(params.map(_._2), dRet), AbsExp(params, ex))
        case _ => None
    }

    // ------------------------------------------------------------------
    // Option combinators
    // ------------------------------------------------------------------

    private def allOf[A](oas: List[Option[A]]): Option[List[A]] =
        oas.foldRight[Option[List[A]]](Some(Nil)) { (oa, acc) =>
            acc flatMap { as => oa map (_ +: as) }
        }

    private def lift2[A, B, C](oa: Option[A], ob: Option[B])(f: (A, B) => C): Option[C] =
        for {
            a <- oa
            b <- ob
        } yield f(a, b)

    private def lift3[A, B, C, D](oa: Option[A], ob: Option[B], oc: Option[C])(f: (A, B, C) => D): Option[D] =
        for {
            a <- oa
            b <- ob
            c <- oc
        } yield f(a, b, c)

    private def unary(rest: List[Raw])(f: Exp => Exp): Option[Exp] = rest match {
        case List(e) => interpret(e) map f
        case _ => None
    }
}
